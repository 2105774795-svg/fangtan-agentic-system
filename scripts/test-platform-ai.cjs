// Deterministic UI + real queue/SSE tests. Start serve-platform-test.py first.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve('data/qa/platform-ai');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    for (let attempt = 0; attempt < 30; attempt++) {
      if (await page.request.get('http://127.0.0.1:18998/api/platform/capabilities').then(r => r.ok()).catch(() => false)) break;
      await page.waitForTimeout(300);
    }
    await page.goto('http://127.0.0.1:18998/');
    await page.getByLabel('今天您想调研什么？').fill('锦州市市场调研');
    await page.getByRole('button', { name: '开始调研', exact: true }).click();
    await page.locator('.live-generation .streamed-response').waitFor();
    assert.equal(await page.locator('.briefing-card').count(), 0, 'choices wait for the actual stream to finish');
    assert.equal(await page.locator('.map-branch').count(), 0, 'no invented stage before the first reply');
    const intakePartial = await page.locator('.live-generation .streamed-response').textContent();
    assert.ok(intakePartial.length > 0 && intakePartial.length < '已识别锦州。请选择行业、目标和受访对象。'.length);
    await page.getByText('已识别锦州。请选择行业、目标和受访对象。', { exact: true }).waitFor();
    await page.locator('.briefing-card').waitFor();
    assert.equal(await page.locator('.scene-switch').count(), 0);
    assert.equal(await page.locator('.branch-planned').count(), 0);
    assert.equal(await page.locator('button[type=submit]').count(), 1);
    assert.equal(await page.locator('.map-branch').count(), 1);
    assert.equal(await page.getByLabel('调研城市').inputValue(), '锦州');
    await page.getByRole('radio', { name: '消费零售', exact: true }).click();
    await page.getByRole('checkbox', { name: '了解市场现状', exact: true }).click();
    await page.getByRole('checkbox', { name: '商户 / 店主', exact: true }).click();
    await page.getByRole('button', { name: '确认需求，生成计划', exact: true }).click();
    await page.locator('.live-generation .streamed-response').waitFor();
    assert.equal(await page.locator('.briefing-card').count(), 0);
    assert.equal(await page.getByRole('button', {name: '确认计划，生成提纲', exact: true}).count(), 0);
    assert.equal(await page.locator('.map-branch').count(), 1, 'background node waits for a saved result');
    const partial = await page.locator('.live-generation .streamed-response').textContent();
    assert.ok(partial.length > 0);
    await page.screenshot({ path: path.join(output, '01-live-output.png'), animations: 'disabled' });
    await page.reload();
    await page.getByRole('button', { name: '确认计划，生成提纲', exact: true }).click();
    await page.getByRole('button', { name: '勾选提纲，准备访谈', exact: true }).click();
    await page.getByRole('button', { name: '粘贴文字材料', exact: true }).click();
    await page.getByPlaceholder('例如：店主访谈 · 第一场').fill('合成访谈材料');
    await page.getByLabel('原始材料正文').fill('受访者建议延长营业时间，但尚未开展试行。\n采访者记录该建议需要后续核实。');
    await page.getByRole('button', { name: '保存原始材料', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('textarea[aria-label="原始材料正文"]')?.value === '');
    await page.getByRole('button', { name: '调研底图', exact: true }).click();
    await page.getByRole('button', { name: '根据原始材料生成分析', exact: true }).click();
    await page.getByRole('button', { name: '生成报告草稿', exact: true }).waitFor();
    const snapshot = await page.evaluate(async () => { const id = new URLSearchParams(location.search).get('project'); return (await (await fetch(`/api/platform/projects/${id}`)).json()); });
    const analysis = snapshot.artifacts.find(a => a.step === 4);
    assert.equal(snapshot.messages.find(m => m.artifact_id === analysis.id).text, analysis.content, 'conversation and canvas refer to the same output');
    assert.equal(await page.locator('.branch-planned').count(), 0);
    await page.getByRole('button', { name: '综合分析 · AI 草稿', exact: true }).click();
    await page.getByRole('button', { name: '[M1-P1]', exact: true }).click();
    await page.locator('.focused-evidence').waitFor();
    assert.ok((await page.locator('.focused-evidence').textContent()).includes('延长营业时间'));
    await page.screenshot({ path: path.join(output, '02-evidence.png'), animations: 'disabled' });
    await page.getByRole('button', { name: '返回画布', exact: true }).click();
    await page.getByRole('button', { name: '生成报告草稿', exact: true }).click();
    await page.getByRole('button', { name: '确认归档', exact: true }).click();
    await page.getByRole('button', { name: '导出归档成果', exact: true }).waitFor();
    assert.equal(await page.locator('.map-branch').count(), 6);
    await page.getByRole('button', { name: '适应全部节点', exact: true }).click();
    assert.equal(await page.getByTestId('rf__edge-branch-1').getAttribute('aria-label'), 'Edge from 0 to 1');
    assert.equal(await page.getByTestId('rf__edge-branch-5').getAttribute('aria-label'), 'Edge from 4 to 5');
    const arranged = page.waitForResponse(r => r.url().endsWith('/layout') && r.request().method() === 'PUT');
    await page.getByRole('button', { name: '整理为顺序流程', exact: true }).click();
    assert.equal((await arranged).status(), 200);
    await page.reload();
    await page.getByRole('button', { name: '导出归档成果', exact: true }).waitFor();
    const layout = await page.evaluate(async () => { const id = new URLSearchParams(location.search).get('project'); return (await (await fetch(`/api/platform/projects/${id}`)).json()).layout.positions; });
    for (let i = 1; i < 6; i++) assert.ok(layout[String(i)].y > layout[String(i - 1)].y, 'sequential layout is persisted');
    await page.getByLabel('给体察助手补充信息').fill('请解释如何核实材料中的建议');
    await page.getByRole('button', { name: '发送补充意见', exact: true }).click();
    await page.getByRole('button', { name: '停止生成', exact: true }).click();
    await page.getByRole('button', { name: '重试', exact: true }).click();
    await page.getByRole('heading', { name: 'chat 测试草稿', exact: true }).last().waitFor();
    await page.waitForFunction(async () => { const id = new URLSearchParams(location.search).get('project'); return (await (await fetch(`/api/platform/projects/${id}`)).json()).job?.status === 'ready'; }, {}, { polling: 300, timeout: 20000 });
    await page.reload();
    await page.getByRole('button', { name: '导出归档成果', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, '03-complete.png'), animations: 'disabled' });
    assert.deepEqual(errors, []);
    console.log('PASS: AI queue, SSE partial output, refresh recovery, progressive nodes, text import, analysis, evidence navigation, report, archive, cancel and retry. (model mocked; no paid calls)');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
