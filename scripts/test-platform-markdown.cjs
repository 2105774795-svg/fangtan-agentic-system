// Isolated model fixture: Markdown rendering + known context + custom selections.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = 'http://127.0.0.1:18998';

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.getByLabel('今天您想调研什么？').fill('我想调研上海新能源汽车的市场情况');
    await page.getByRole('button', { name: '开始调研', exact: true }).click();
    const live = page.locator('.streamed-response');
    await live.locator('strong').first().waitFor();
    assert.equal(await page.locator('.briefing-card').count(), 0, 'checklist waits for final stream');
    assert.ok(!(await live.textContent()).includes('**'), 'incomplete bold does not expose markers');
    await page.locator('.briefing-card').waitFor();
    assert.equal(await page.getByRole('navigation', { name: '调研工具', exact: true }).count(), 0);
    assert.equal(await page.locator('.brief-form fieldset').count(), 2, 'known industry is not asked again');
    assert.ok((await page.locator('.resolved-context').textContent()).includes('新能源汽车'));
    const goal = page.locator('.brief-form fieldset').nth(0);
    const audience = page.locator('.brief-form fieldset').nth(1);
    await goal.getByRole('checkbox', { name: '其他', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '确认需求，生成计划', exact: true }).isDisabled(), true);
    await page.getByLabel('其他调研目的', { exact: true }).fill('评估上海充电服务的商业机会');
    await audience.getByRole('checkbox', { name: '消费者', exact: true }).click();
    await audience.getByRole('checkbox', { name: '其他', exact: true }).click();
    await page.getByLabel('其他受访对象', { exact: true }).fill('充电站运营方');
    assert.ok((await page.locator('.map-branch').textContent()).includes('评估上海充电服务的商业机会'));
    await page.waitForFunction(() => document.querySelector('.map-branch')?.textContent.includes('充电站运营方'));
    assert.ok((await page.locator('.map-branch').textContent()).includes('充电站运营方'));
    await page.screenshot({ path: 'data/qa/platform-ai/custom-checklist.png', animations: 'disabled' });
    await page.getByRole('button', { name: '确认需求，生成计划', exact: true }).click();
    await page.getByRole('button', { name: '确认计划，生成提纲', exact: true }).waitFor();
    const id = new URL(page.url()).searchParams.get('project');
    const project = await (await page.request.get(`${base}/api/platform/projects/${id}`)).json();
    assert.deepEqual(project.answers.industry, ['新能源汽车']);
    assert.deepEqual(project.answers.goal, ['评估上海充电服务的商业机会']);
    assert.deepEqual(project.answers.audience, ['消费者', '充电站运营方']);
    const last = page.locator('.studio-message.assistant').last();
    assert.equal(await last.getByRole('heading', { name: '研究方向', exact: true }).count(), 1);
    assert.equal(await last.locator('strong').filter({ hasText: '重点内容' }).count(), 1);
    assert.ok(await last.locator('li').count() >= 2);
    assert.equal(await last.locator('table').count(), 1);
    assert.ok((await last.locator('pre code').textContent()).includes('**字面符号**'), 'literal code stays literal');
    assert.ok(project.messages.some(m => m.text.includes('**重点内容**')), 'original Markdown remains stored');
    const artifact = project.artifacts.find(a => a.step === 1);
    await page.getByRole('button', { name: artifact.title, exact: true }).click();
    const doc = page.locator('.markdown-document');
    assert.equal(await doc.getByRole('heading', { name: '研究方向', exact: true }).count(), 1);
    assert.equal(await doc.locator('table').count(), 1);
    await page.screenshot({ path: 'data/qa/platform-ai/markdown-document.png', animations: 'disabled' });
    await page.getByRole('button', { name: '返回画布', exact: true }).click();
    await page.getByLabel('给体察助手补充信息').fill('在背景与计划模块新加文档，生成一份访谈行程安排');
    await page.getByRole('button', { name: '发送补充意见', exact: true }).click();
    await page.locator('.document-created').waitFor();
    const updated = await (await page.request.get(`${base}/api/platform/projects/${id}`)).json();
    assert.equal(updated.stage, project.stage);
    assert.deepEqual(updated.artifacts.find(a => a.id === artifact.id), artifact, 'original file remains unchanged');
    const added = updated.artifacts.find(a => a.kind === 'document');
    assert.equal(added.step, 1);
    assert.equal(added.title, '访谈行程安排');
    await page.reload();
    await page.getByRole('button', { name: '访谈行程安排', exact: true }).click();
    await page.locator('.markdown-document').getByRole('heading', { name: '访谈行程安排', exact: true }).waitFor();
    await page.screenshot({ path: 'data/qa/platform-ai/agent-document.png', animations: 'disabled' });
    assert.deepEqual(errors, []);
    console.log('PASS: formatted streamed Markdown + saved documents, known industry skipped, editable other goal/audience, agent-created document in the requested module without overwriting or advancing.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
