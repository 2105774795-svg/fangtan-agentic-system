// Run against a dedicated server and synthetic database, never the daily service.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const base = process.env.PLATFORM_TEST_URL || 'http://127.0.0.1:18996';
const output = path.resolve(__dirname, '../data/qa/platform');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  const authRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/\/api\/(auth|memoir\/auth)/.test(r.url())) authRequests.push(r.url()); });
  await page.goto(base);
  await page.getByRole('heading', { name: '让每一次对话，都有迹可循。' }).waitFor();
  await page.getByRole('button', { name: '开始调研' }).waitFor();
  await page.screenshot({ path: path.join(output, '01-home.png'), fullPage: true });
  const alpha = () => page.getByTestId('reveal-mask').evaluate(canvas => {
    const ratio = canvas.width / canvas.clientWidth;
    return canvas.getContext('2d').getImageData(Math.round(180 * ratio), Math.round(290 * ratio), 1, 1).data[3];
  });
  assert.equal(await alpha(), 255, 'image starts covered');
  const rect = await page.locator('.landing-hero').boundingBox();
  await page.mouse.move(180, rect.y + 290);
  await page.waitForTimeout(160);
  assert.ok(await alpha() < 180, 'pointer actually erases canvas alpha');
  await page.waitForTimeout(1600);
  assert.equal(await alpha(), 255, 'cover recovers after trail fades');
  await page.getByRole('button', { name: /移动光标，探索底图/ }).click();
  await page.screenshot({ path: path.join(output, '02-home-relief.png'), fullPage: true });
  await page.getByRole('button', { name: /恢复光标擦除/ }).click();
  await page.getByLabel('今天您想调研什么？').fill('锦州消费市场调研 · 浏览器验收');
  await page.getByRole('button', { name: '开始调研' }).click();
  await page.getByRole('heading', { name: '把思路，一步步展开。' }).waitFor();
  await page.locator('.flow-step').first().waitFor({ state: 'visible' });
  await page.getByRole('radio', { name: '消费零售', exact: true }).click();
  await page.getByRole('checkbox', { name: '了解市场现状', exact: true }).click();
  await page.getByRole('checkbox', { name: '商户 / 店主', exact: true }).click();
  await page.getByLabel('补充信息', { exact: true }).fill('锦州古塔区，访谈 5 位店主');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await page.getByRole('button', { name: '草稿已保存', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('radio', { name: '消费零售', exact: true }).waitFor();
  await page.locator('.flow-step').first().waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('radio', { name: '消费零售', exact: true }).getAttribute('aria-checked'), 'true');
  assert.equal(await page.getByLabel('补充信息', { exact: true }).inputValue(), '锦州古塔区，访谈 5 位店主');
  await page.screenshot({ path: path.join(output, '03-workspace-choices.png'), fullPage: true });
  await page.getByRole('button', { name: '确认，展开调研', exact: true }).click();
  await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).waitFor();
  await page.locator('.flow-step.active').waitFor({ state: 'visible' });
  await page.screenshot({ path: path.join(output, '04-workspace-flow.png'), fullPage: true });
  await page.getByText('背景与计划 · 示例草稿', { exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.getByLabel('成果正文');
  const original = await editor.inputValue();
  await editor.fill(original + '\n\n## 人工补充\n优先访谈经营满五年的店主。');
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await page.getByText('已保存新版本', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, '05-artifact.png'), fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载成果', exact: true }).click();
  assert.ok((await downloadPromise).suggestedFilename().endsWith('.md'));
  await page.getByRole('button', { name: '查看版本历史', exact: true }).click();
  await page.getByText('载入到编辑器', { exact: true }).waitFor();
  await page.getByRole('button', { name: '返回画布', exact: true }).click();
  await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).click();
  await page.getByRole('button', { name: '确认提纲，进入采集准备', exact: true }).click();
  await page.getByRole('button', { name: '导出当前准备成果', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: '导出当前准备成果', exact: true }).waitFor();
  await page.getByRole('button', { name: /^项目资料/ }).click();
  await page.getByText('现场采集准备清单', { exact: true }).waitFor();
  await page.getByRole('button', { name: '访谈记录', exact: true }).click();
  await page.getByText('录音、材料导入和手机采集将在第二轮接入。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '历史项目', exact: true }).click();
  await page.getByPlaceholder('搜索项目名称').fill('不存在的项目');
  await page.getByText('没有找到相关项目', { exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  for (const [scene, radio, goal, audience] of [
    ['enterprise', '制造业', '经营挑战', '企业高管'],
    ['memoir', '童年与故乡', '家族记忆', '个人回忆录'],
  ]) {
    await page.getByRole('button', { name: '新建调研', exact: true }).click();
    await page.locator('.scenario-suggestions').getByRole('button', { name: scene === 'memoir' ? /口述史/ : /企业访谈/ }).click();
    await page.getByRole('button', { name: '开始调研' }).click();
    await page.getByRole('radio', { name: radio, exact: true }).click();
    await page.getByRole('checkbox', { name: goal, exact: true }).click();
    await page.getByRole(scene === 'memoir' ? 'radio' : 'checkbox', { name: audience, exact: true }).click();
    await page.getByRole('button', { name: '确认，展开调研', exact: true }).click();
    await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).waitFor();
  }
  await page.getByRole('button', { name: '新建调研', exact: true }).click();
  await page.getByRole('button', { name: '切换深色模式', exact: true }).click();
  await page.screenshot({ path: path.join(output, '06-dark.png'), fullPage: true });
  await page.getByRole('button', { name: '切换浅色模式', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, '07-mobile-home.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile home has no horizontal overflow');
  await page.getByRole('button', { name: /我的项目/ }).click();
  await page.getByPlaceholder('搜索项目名称').fill('锦州消费');
  await page.locator('.history-list .project-row').first().click();
  await page.getByRole('button', { name: '导出当前准备成果', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, '08-mobile-chat.png'), fullPage: true });
  await page.getByRole('button', { name: '收起助手', exact: true }).click();
  await page.screenshot({ path: path.join(output, '09-mobile-flow.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile workspace has no horizontal overflow');
  const reduced = await browser.newContext({ reducedMotion: 'reduce' });
  const reducedPage = await reduced.newPage();
  await reducedPage.goto(base);
  await reducedPage.getByTestId('reveal-mask').waitFor({ state: 'attached' });
  assert.equal(await reducedPage.getByTestId('reveal-mask').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  assert.deepEqual(errors, [], 'no unhandled browser errors');
  assert.deepEqual(authRequests, [], 'new workspace never calls authentication');
  await browser.close();
  console.log('PASS: reveal, three scenes, persistence, artifacts, versions, downloads, history, dark mode, mobile, reduced motion, no authentication.');
})().catch(error => { console.error(error); process.exit(1); });
