// Run against a dedicated server and synthetic database, never the daily service.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const base = process.env.PLATFORM_TEST_URL || 'http://127.0.0.1:18996';
const output = path.resolve(__dirname, '../data/qa/platform');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  const authRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/\/api\/(auth|memoir\/auth)/.test(r.url())) authRequests.push(r.url()); });
  await page.route('**/api/platform/projects', async route => {
    if (route.request().method() !== 'POST') return route.continue();
    const body = route.request().postDataJSON();
    await route.continue({ postData: JSON.stringify({ ...body, mode: 'demo' }) });
  });
  await page.goto(base);
  await page.getByRole('heading', { name: '让每一次对话，都有迹可循。' }).waitFor();
  await page.getByRole('button', { name: '开始调研' }).waitFor();
  await page.screenshot({ path: path.join(output, '01-home.png'), fullPage: true, animations: 'disabled' });
  const alpha = () => page.getByTestId('reveal-mask').evaluate(canvas => {
    const ratio = canvas.width / canvas.clientWidth;
    return canvas.getContext('2d').getImageData(Math.round(180 * ratio), Math.round(290 * ratio), 1, 1).data[3];
  });
  assert.equal(await alpha(), 255, 'image starts covered');
  const rect = await page.locator('.landing-hero').boundingBox();
  await page.mouse.move(180, rect.y + 290);
  await page.waitForTimeout(160);
  assert.ok(await alpha() < 180, 'pointer actually erases canvas alpha');
  await page.waitForTimeout(1600);
  assert.equal(await alpha(), 255, 'cover recovers after trail fades');
  await page.getByRole('button', { name: /移动光标，探索底图/ }).click();
  await page.screenshot({ path: path.join(output, '02-home-relief.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: /恢复光标擦除/ }).click();
  await page.getByLabel('今天想准备哪一次对话？').fill('锦州市市场调研');
  await page.getByRole('button', { name: '开始调研' }).click();
  await page.getByTestId('research-map').waitFor();
  await page.locator('.map-branch').first().waitFor({ state: 'visible' });
  assert.equal(await page.locator('.map-branch').count(), 1, 'unreached stages are hidden initially');
  await page.waitForTimeout(350);
  const dragHeader = page.locator('.branch-drag-handle').first();
  const dragRect = await dragHeader.boundingBox();
  await page.mouse.move(dragRect.x + 80, dragRect.y + 20);
  await page.mouse.down();
  await page.mouse.move(dragRect.x + 150, dragRect.y + 70, { steps: 8 });
  const layoutSaved = page.waitForResponse(r => r.url().endsWith('/layout') && r.request().method() === 'PUT');
  await page.mouse.up();
  assert.equal((await layoutSaved).status(), 200);
  const savedLayout = await page.evaluate(async () => { const id = new URLSearchParams(location.search).get('project'); return (await (await fetch(`/api/platform/projects/${id}`)).json()).layout; });
  await page.getByRole('radio', { name: '消费零售', exact: true }).click();
  await page.getByRole('checkbox', { name: '了解市场现状', exact: true }).click();
  await page.getByRole('checkbox', { name: '商户 / 店主', exact: true }).click();
  await page.getByLabel('给体察助手补充信息', { exact: true }).fill('锦州古塔区，访谈 5 位店主');
  // Only the unified composer submits; draft choices remain local until confirmation.
  assert.equal(await page.locator('.studio-composer button[type=submit]').count(), 1);
  assert.equal(await page.locator('.branch-planned').count(), 0);
  await page.screenshot({ path: path.join(output, '03-workspace-choices.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '确认需求，生成计划', exact: true }).click();
  await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).waitFor();
  const restoredLayout = await page.evaluate(async () => { const id = new URLSearchParams(location.search).get('project'); return (await (await fetch(`/api/platform/projects/${id}`)).json()).layout; });
  assert.deepEqual(restoredLayout, savedLayout, 'node drag layout survives confirmation and refresh');
  await page.locator('.map-branch.state-active').waitFor({ state: 'visible' });
  await page.screenshot({ path: path.join(output, '04-workspace-flow.png'), fullPage: true, animations: 'disabled' });
  assert.equal(await page.locator('.map-project').count(), 1, 'project center exists');
  assert.equal(await page.locator('.map-branch').count(), 2, 'only reached branches appear');
  assert.ok((await page.locator('.research-map').boundingBox()).y < 70, 'canvas starts directly below top bar');
  await page.getByRole('tab', { name: '资料', exact: true }).click();
  await page.locator('.assistant-materials').waitFor();
  assert.equal(await page.locator('.side-file').count(), 2);
  await page.screenshot({ path: path.join(output, '10-studio-sources.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('tab', { name: /^任务/ }).click();
  assert.equal(await page.locator('.task-item').count(), 2);
  await page.getByRole('tab', { name: '见解', exact: true }).click();
  await page.getByRole('heading', { name: '已确认的关注方向', exact: true }).waitFor();
  await page.getByRole('tab', { name: '调研对话', exact: true }).click();
  const initialZoom = Number.parseInt(await page.locator('.zoom-value').textContent());
  await page.getByRole('button', { name: '放大画布', exact: true }).click();
  await page.waitForTimeout(250);
  assert.ok(Number.parseInt(await page.locator('.zoom-value').textContent()) > initialZoom);
  await page.getByRole('button', { name: '适应全部节点', exact: true }).click();
  await page.getByRole('button', { name: '切换缩略图', exact: true }).click();
  await page.locator('.react-flow__minimap').waitFor();
  await page.getByRole('button', { name: '切换缩略图', exact: true }).click();
  const separator = page.getByRole('separator', { name: '调整助手宽度' });
  const originalWidth = (await page.locator('.studio-assistant').boundingBox()).width;
  await separator.focus();
  await page.keyboard.press('ArrowLeft');
  assert.ok((await page.locator('.studio-assistant').boundingBox()).width > originalWidth);
  await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: '背景与计划 · 示例草稿', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.getByLabel('成果正文');
  const original = await editor.inputValue();
  await editor.fill(original + '\n\n## 人工补充\n优先访谈经营满五年的店主。');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: '项目概览', exact: true }).click();
  assert.ok((await editor.inputValue()).includes('优先访谈经营满五年的店主。'), 'cancel navigation preserves draft');
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await page.getByText('已保存新版本', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, '05-artifact.png'), fullPage: true, animations: 'disabled' });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载成果', exact: true }).click();
  assert.ok((await downloadPromise).suggestedFilename().endsWith('.md'));
  await page.getByRole('button', { name: '查看版本历史', exact: true }).click();
  await page.getByText('载入到编辑器', { exact: true }).waitFor();
  await page.getByRole('button', { name: '返回画布', exact: true }).click();
  await page.getByRole('button', { name: '引用项目成果', exact: true }).click();
  await page.locator('.reference-menu').getByRole('button', { name: '需求确认单', exact: true }).click();
  assert.ok((await page.getByLabel('给体察助手补充信息').inputValue()).includes('参考《需求确认单》'));
  await page.getByLabel('给体察助手补充信息').fill('');
  await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).click();
  await page.getByRole('button', { name: '确认提纲，进入采集准备', exact: true }).click();
  await page.getByRole('button', { name: '导出当前成果', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: '导出当前成果', exact: true }).waitFor();
  await page.getByRole('button', { name: /^项目资料/ }).click();
  await page.getByText('现场采集准备清单', { exact: true }).waitFor();
  await page.getByRole('navigation', { name: '工作空间' }).getByRole('button', { name: /^现场采集/ }).click();
  await page.getByText('先确认调研提纲', { exact: true }).waitFor();
  await page.getByRole('button', { name: '历史项目', exact: true }).click();
  await page.getByPlaceholder('搜索项目名称').fill('不存在的项目');
  await page.getByText('没有找到相关项目', { exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  for (const [scene, radio, goal, audience] of [
    ['enterprise', '制造业', '经营挑战', '企业高管'],
    ['memoir', '童年与故乡', '家族记忆', '个人回忆录'],
  ]) {
    await page.getByRole('button', { name: '新建调研', exact: true }).click();
    await page.locator('.scenario-suggestions').getByRole('button', { name: scene === 'memoir' ? /口述史/ : /企业访谈/ }).click();
    await page.getByRole('button', { name: '开始调研' }).click();
    await page.getByRole('radio', { name: radio, exact: true }).click();
    await page.getByRole('checkbox', { name: goal, exact: true }).click();
    await page.getByRole(scene === 'memoir' ? 'radio' : 'checkbox', { name: audience, exact: true }).click();
    await page.getByRole('button', { name: '确认需求，生成计划', exact: true }).click();
    await page.getByRole('button', { name: '确认计划，生成提纲示例', exact: true }).waitFor();
  }
  await page.getByRole('button', { name: '新建调研', exact: true }).click();
  await page.getByRole('button', { name: '切换深色模式', exact: true }).click();
  await page.screenshot({ path: path.join(output, '06-dark.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: /我的项目/ }).click();
  await page.getByPlaceholder('搜索项目名称').fill('');
  await page.locator('.history-list .project-row').first().click();
  await page.locator('.map-branch').first().waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.getByRole('tab', { name: /^任务/ }).click();
  await page.screenshot({ path: path.join(output, '11-studio-dark.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '新建调研', exact: true }).click();
  await page.getByRole('button', { name: '切换浅色模式', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, '07-mobile-home.png'), fullPage: true, animations: 'disabled' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile home has no horizontal overflow');
  await page.getByRole('button', { name: /我的项目/ }).click();
  await page.getByPlaceholder('搜索项目名称').fill('锦州市');
  await page.locator('.history-list .project-row').first().click();
  await page.getByRole('button', { name: '导出当前成果', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, '08-mobile-chat.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '收起助手', exact: true }).click();
  await page.screenshot({ path: path.join(output, '09-mobile-flow.png'), fullPage: true, animations: 'disabled' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile workspace has no horizontal overflow');
  const reduced = await browser.newContext({ reducedMotion: 'reduce' });
  const reducedPage = await reduced.newPage();
  await reducedPage.goto(base);
  await reducedPage.getByTestId('reveal-mask').waitFor({ state: 'attached' });
  assert.equal(await reducedPage.getByTestId('reveal-mask').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  assert.deepEqual(errors, [], 'no unhandled browser errors');
  assert.deepEqual(authRequests, [], 'new workspace never calls authentication');
  await browser.close();
  console.log('PASS: reveal, three scenes, persistence, artifacts, versions, downloads, history, progressive nodes, persistent dragging, four assistant tabs, zoom/minimap, assistant resize, draft guard, references, dark workspace, mobile, reduced motion, no authentication.');
})().catch(error => { console.error(error); process.exit(1); });
